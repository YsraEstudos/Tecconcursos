const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const childProcess = require("node:child_process");

const projectRoot = path.resolve(__dirname, "../..");
const buildScript = path.join(projectRoot, "scripts", "build-userscript.cjs");
const bundlePath = path.join(projectRoot, "tecconcursos-scraper.user.js");

test("bundle tem metadata válida, rota de caderno e atualização", () => {
  childProcess.execFileSync(process.execPath, [buildScript], { cwd: projectRoot, stdio: "pipe" });
  const bundle = fs.readFileSync(bundlePath, "utf8");
  assert.match(bundle, /^\/\/ ==UserScript==/);
  assert.match(bundle, /\/\/ ==\/UserScript==/);
  assert.match(bundle, /@version\s+2\.7\.0/);
  assert.match(bundle, /@match\s+https:\/\/www\.tecconcursos\.com\.br\/\*/);
  assert.match(bundle, /@match\s+https:\/\/tecconcursos\.com\.br\/\*/);
  assert.match(bundle, /@run-at\s+document-start/);
  assert.match(bundle, /@match\s+https:\/\/www\.tecconcursos\.com\.br\/questoes\/cadernos\/\*/);
  assert.match(bundle, /@match\s+https:\/\/www\.tecconcursos\.com\.br\/questoes\/pastas\*/);
  assert.match(bundle, /@updateURL\s+https:\/\/raw\.githubusercontent\.com\/YsraEstudos\/Tecconcursos\/main\/tecconcursos-scraper\.user\.js/);
  assert.match(bundle, /\/api\/cadernos\//);
  assert.match(bundle, /numeroAlternativaCorreta/);
  assert.match(bundle, /Gabarito:/);
  assert.match(bundle, /Biblioteca de Cadernos/);
  assert.match(bundle, /AI Context/);
  assert.match(bundle, /Universal Agent Guidelines/);
  assert.match(bundle, /TecConcursos — Contexto operacional observado/);
  assert.match(bundle, /Imprimir Caderno/);
  assert.match(bundle, /suppressNativePrintOnOutputPage/);
  assert.match(bundle, /print-blocker\.cjs/);
  assert.match(bundle, /automation-controls\.cjs/);
  assert.match(bundle, /Baixar log detalhado/);
  assert.match(bundle, /Assumir execução/);
  assert.match(bundle, /automation-lock\.cjs/);
  assert.match(bundle, /automation-dom\.cjs/);
  assert.match(bundle, /tampermonkey-menu\.cjs/);
  assert.match(bundle, /@grant\s+GM_registerMenuCommand/);
  assert.match(bundle, /@grant\s+GM_unregisterMenuCommand/);
  assert.match(bundle, /Parar automação/);
  assert.match(bundle, /tec-library-pause/);
  assert.match(bundle, /Reiniciar busca de materiais/);
  assert.match(bundle, /Retomar automação/);
  assert.match(bundle, /id="feedback"/);
  assert.match(bundle, /\.option\.correct/);
  assert.match(bundle, /xl\/media\/image/);
  assert.match(bundle, /credentials:\s*["']include["']/);
  assert.match(bundle, /gabarito desta questão não foi extraído/);
  assert.match(bundle, /@grant\s+unsafeWindow/);
  assert.match(bundle, /@grant\s+GM_addElement/);
  assert.match(bundle, /state\.export\s+&&\s+state\.export\.job/);
  assert.doesNotMatch(bundle, /@require/);
  childProcess.execFileSync(process.execPath, ["--check", bundlePath], { cwd: projectRoot, stdio: "pipe" });
});
